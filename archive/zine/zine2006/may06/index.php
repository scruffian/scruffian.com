      Perhaps I could also defend my recent comments about blogs. For internet
      geeks only:<br>
      <br>
      <br> <h5>The Weblog</h5>
      I think blogs are useful tools and have their place on the internet. They
      are quick and easy to update and can be managed by more than one person.
      If this means they are updated more often and more emphasis is put on the
      quality of the update than trying to work out how to write html then that
      is good. Its much better to do that stuff quickly so you can spend more
      time on your bike.<br>
      <br>
      However I think these days sometimes people just jump on the blog bandwagon
      without thinking why and it can actually cause them more hassle than it
      solves. Also I think blogs can have a tendancy to distract from other aspects
      of web design which can be fun, and make a site more interesting to look
      at. After a few year of looking at blogs which just have 10 pictures of
      different box tricks you get a bit bored of it. Caption really help with
      this. I like to have a story to read. I would like to put more captions
      on my pictures but it takes time and I am lazy. But also what helps to make
      it more interesting is different designs people use to present the content.
      Finding you way around new designs is good for lots of reasons which I cant
      be bothered to list, because I am sure you agree anyway.<br>
      <br>
      So the point is blogs aren't bad but if you can do something better then
      why not. <a href="http://www.theshovelload.com/zinesnovember/zinenov29.html">For
      example.</a></p>
