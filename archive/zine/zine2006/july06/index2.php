<p>15th July<br>The meeting last night was pretty interesting. It sounded like there might be some sort of compromise between people who want to use the trails and people who want to use the wood for other things, but KCC didn't even bother turning up and its their land, so in a way the meeting was a bit pointelss.<br><br>
What was really good though was how many riders turned up to support the trails, and how well behaved they were. Before the meeting we were asked to be polite and listen to each other and only make constuctive comments. It was really interesting to see half the room, full of young, angry, riders keeping their cool and staying polite and civil, while the other half of the room, full of "well to do", well educated residents, embarrased themselves by heckling the BMXers whenever they spoke, interupting and being insulting and rude. All of the riders were respectful, didn't chat amongst themselves, (unlike the residents again) and listened to what other people were saying. It made me feel proud to be part of this group of people.</p>
